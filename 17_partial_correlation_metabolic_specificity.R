# ============================================================
# 17_partial_correlation_metabolic_specificity.R
#
# Supplementary Figure S21:
# Metabolic pathway specificity of SPP1 and MIF ligand expression
# in tumor-derived hepatocytes.
#
# Final manuscript-locked purpose:
#   Compute partial Spearman correlations between ligand expression
#   and glycolysis or OXPHOS activity in tumor-derived hepatocytes.
#
# Locked inputs:
#   input object: seurat_final.rds
#   patient_col  = "patient"
#   celltype_col = "cell_type"
#   site_col     = "site"
#   gly_col      = "Glycolysis_AUC"
#
# Locked selection:
#   tumor-derived hepatocytes:
#     site == "Tumor" & cell_type == "Hepatocyte"
#   expected n = 15,391
#
# Locked method:
#   OXPHOS_AUC is read from the S21 source generated by
#   14_OXPHOS_metabolic_specificity.R if available.
#   If that source file is absent, OXPHOS_AUC is computed here
#   using the same 39-gene OXPHOS set and AUCell parameters.
#
#   Partial Spearman correlations are computed using ppcor::pcor.test:
#     SPP1 ~ Glycolysis_AUC | OXPHOS_AUC
#     SPP1 ~ OXPHOS_AUC    | Glycolysis_AUC
#     MIF  ~ Glycolysis_AUC | OXPHOS_AUC
#     MIF  ~ OXPHOS_AUC    | Glycolysis_AUC
#
# Locked manuscript checkpoints:
#   Glycolysis-OXPHOS Spearman rho approximately 0.066
#   SPP1 glycolysis partial rho approximately 0.227
#   SPP1 OXPHOS partial rho approximately 0.125
#   MIF  glycolysis partial rho approximately 0.105
#   MIF  OXPHOS partial rho approximately 0.242
#
# Mandatory output order:
#   1. Source CSV files
#   2. QC CSV file
#   3. PDF/PNG only if QC PASS
#
# Figure note:
#   No "Supplementary Figure S21" title is printed inside the figure.
# ============================================================

