qc_row <- function(check, observed, expected, pass, tolerance = NA_character_) {
  tibble::tibble(
    check = check,
    observed = as.character(observed),
    expected = as.character(expected),
    tolerance = as.character(tolerance),
    pass = as.logical(pass)
  )
}

get_counts_mat <- function(seu, assay) {
  tryCatch(
    {
      SeuratObject::LayerData(seu, assay = assay, layer = "counts")
    },
    error = function(e) {
      Seurat::GetAssayData(seu, assay = assay, slot = "counts")
    }
  )
}

get_norm_mat <- function(seu, assay) {
  tryCatch(
    {
      SeuratObject::LayerData(seu, assay = assay, layer = "data")
    },
    error = function(e) {
      Seurat::GetAssayData(seu, assay = assay, slot = "data")
    }
  )
}

format_p <- function(x) {
  ifelse(is.na(x), NA_character_,
         ifelse(x == 0, "<1e-300", sprintf("%.3e", x)))
}

partial_spearman_ppcor <- function(dat, ligand, metabolic_program, adjusted_for) {
  x <- dat[[ligand]]
  y <- dat[[metabolic_program]]
  z <- dat[[adjusted_for]]

  ok <- stats::complete.cases(x, y, z)
  x <- x[ok]
  y <- y[ok]
  z <- z[ok]

  if (length(x) < 10) {
    return(tibble::tibble(
      ligand = ligand,
      metabolic_program = metabolic_program,
      adjusted_for = adjusted_for,
      n_cells = length(x),
      partial_spearman_rho = NA_real_,
      p_value = NA_real_
    ))
  }

  ct <- ppcor::pcor.test(
    x = x,
    y = y,
    z = z,
    method = "spearman"
  )

  tibble::tibble(
    ligand = ligand,
    metabolic_program = metabolic_program,
    adjusted_for = adjusted_for,
    n_cells = length(x),
    partial_spearman_rho = as.numeric(ct$estimate),
    p_value = as.numeric(ct$p.value)
  )
}

compute_oxphos_auc <- function(counts_mat, cells_use, oxphos_genes) {
  oxphos_present <- intersect(oxphos_genes, rownames(counts_mat))
  oxphos_missing <- setdiff(oxphos_genes, oxphos_present)

  if (length(oxphos_present) < 4) {
    stop("Fewer than 4 OXPHOS genes are present; AUCell scoring is not meaningful.", call. = FALSE)
  }

  expr_counts <- counts_mat[, cells_use, drop = FALSE]
  auc_max_rank <- ceiling(0.05 * nrow(expr_counts))

  rankings <- AUCell::AUCell_buildRankings(
    exprMat = expr_counts,
    plotStats = FALSE,
    verbose = FALSE
  )

  cells_auc <- AUCell::AUCell_calcAUC(
    geneSets = list(OXPHOS = oxphos_present),
    rankings = rankings,
    aucMaxRank = auc_max_rank,
    verbose = FALSE
  )

  auc <- as.numeric(AUCell::getAUC(cells_auc)["OXPHOS", ])
  names(auc) <- colnames(AUCell::getAUC(cells_auc))

  list(
    auc = auc,
    oxphos_present = oxphos_present,
    oxphos_missing = oxphos_missing,
    auc_max_rank = auc_max_rank,
    source = "computed_in_17"
  )
}

